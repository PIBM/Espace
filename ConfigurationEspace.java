    private void aZoneTexteVitesseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_aZoneTexteVitesseActionPerformed
        int lValeur = Integer.parseInt(evt.getActionCommand());
        
        if ((lValeur >= 10) || (lValeur == 0)){
            aLabelVitesse.setText(""+lValeur);
            aInit.asgnVitesseEtoiles(lValeur);
        }
    }//GEN-LAST:event_aZoneTexteVitesseActionPerformed

