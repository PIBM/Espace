    private void aZoneTextePlaneteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_aZoneTextePlaneteActionPerformed
        int lValeur = Integer.parseInt(evt.getActionCommand());
        
        if ((lValeur >= 4*aNbJoueur) && (lValeur <= 500)) {
            aLabelPlanete.setText(""+lValeur);
        }
        
        aInit.reaffiche();
    }//GEN-LAST:event_aZoneTextePlaneteActionPerformed

