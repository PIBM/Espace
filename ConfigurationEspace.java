    private void aZoneTexteEtoilesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_aZoneTexteEtoilesActionPerformed
        int lValeur = Integer.parseInt(evt.getActionCommand());
        
        if ((lValeur >= 0) && (lValeur <= 1000)) {
            aLabelEtoiles.setText(""+lValeur);
            aInit.asgnNbEtoiles(lValeur);
            
            if (lValeur == 0) {
                aLabelVitesse.setText("0");
                aZoneTexteVitesse.setText("0");
                aZoneTexteVitesse.setEnabled(false);
            } else if (aZoneTexteVitesse.isEnabled() == false) {
                aLabelVitesse.setText("50");
                aZoneTexteVitesse.setText("50");
                aZoneTexteVitesse.setEnabled(true);
                aInit.asgnVitesseEtoiles(50);
            }
        }
    }//GEN-LAST:event_aZoneTexteEtoilesActionPerformed

